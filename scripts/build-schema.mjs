import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

/**
 * Concatenate supabase/migrations/*.sql into supabase/schema.sql.
 *
 * The Supabase CLI was not available in the build environment, so the fastest
 * reliable way to apply the schema to a hosted project is one paste into the
 * SQL Editor. This keeps that single file in sync with the migrations, which
 * remain the source of truth.
 *
 *   npm run db:schema
 */
const MIGRATIONS_DIR = join("supabase", "migrations");
const OUTPUT = join("supabase", "schema.sql");

const files = (await readdir(MIGRATIONS_DIR))
  .filter((name) => name.endsWith(".sql"))
  .sort();

const parts = [
  "-- =============================================================================",
  "-- TalentFlow - generated schema bundle. DO NOT EDIT.",
  "--",
  "-- Generated by `npm run db:schema` from supabase/migrations/*.sql, which are",
  "-- the source of truth. Paste this whole file into the Supabase SQL Editor to",
  "-- set up a project in one step. Every statement is idempotent, so running it",
  "-- again is safe.",
  "--",
  `-- Included: ${files.join(", ")}`,
  "-- =============================================================================",
  "",
];

for (const file of files) {
  const sql = await readFile(join(MIGRATIONS_DIR, file), "utf8");
  parts.push(`-- >>> ${file} >>>`, "", sql.trim(), "", `-- <<< ${file} <<<`, "");
}

await writeFile(OUTPUT, `${parts.join("\n")}\n`, "utf8");
console.log(`Wrote ${OUTPUT} from ${files.length} migration file(s).`);
